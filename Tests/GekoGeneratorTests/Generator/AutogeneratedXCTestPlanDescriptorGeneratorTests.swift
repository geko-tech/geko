    func test_map_passesThroughConfigurationAndDefaultOptions() throws {
        // Given
        let (graphTraverser, generatedProjects) = try makeSubjectInputs(
            autogeneratedTestPlans: [
                .testPlan(
                    name: "Plan.xctestplan",
                    configurationOptions: .init(
                        environmentVariableEntries: [.init(key: "isUnitTesting", value: "YES")],
                        targetForVariableExpansion: "AppTests"
                    ),
                    defaultOptions: .init(
                        commandLineArgumentEntries: [.init(argument: "--arg", enabled: true)],
                        targetForVariableExpansion: "FrameworkTests"
                    ),
                    testTargetSelection: .all
                ),
            ]
        )

        // When
        let (descriptors, _) = try subject.autogeneratedXCTestPlanDescriptorsAndGenerateMetadata(
            graphTraverser: graphTraverser,
            generatedProjects: generatedProjects,
            sideTable: .init()
        )

        // Then
        let descriptor = try XCTUnwrap(descriptors.first)
        XCTAssertEqual(descriptor.configurationOptions?.environmentVariableEntries, [.init(key: "isUnitTesting", value: "YES")])
        XCTAssertEqual(descriptor.configurationOptionsTargetForVariableExpansion?.pbxTarget.name, "AppTests")
        XCTAssertEqual(descriptor.defaultOptions?.commandLineArgumentEntries, [.init(argument: "--arg", enabled: true)])
        XCTAssertEqual(descriptor.defaultOptionsTargetForVariableExpansion?.pbxTarget.name, "FrameworkTests")
        XCTAssertEqual(
            descriptor.configurationOptionsTargetForVariableExpansion?.containerPath,
            "container:App.xcodeproj"
        )
        XCTAssertEqual(
            descriptor.defaultOptionsTargetForVariableExpansion?.containerPath,
            "container:Framework/Framework.xcodeproj"
        )
    }

