    // MARK: - Test target selection

    func test_map_whenTestTargetSelection_all_includesAllTestBundleTargets() throws {
        // Given
        let (graphTraverser, generatedProjects) = try makeSubjectInputs(
            autogeneratedTestPlans: [
                .testPlan(name: "All.xctestplan", testTargetSelection: .all),
            ]
        )

        // When
        let (descriptors, _) = try subject.autogeneratedXCTestPlanDescriptorsAndGenerateMetadata(
            graphTraverser: graphTraverser,
            generatedProjects: generatedProjects,
            sideTable: .init()
        )

        // Then
        XCTAssertEqual(descriptors.count, 1)
        let descriptor = try XCTUnwrap(descriptors.first)
        XCTAssertEqual(descriptor.testTargets.count, 2)
        XCTAssertEqual(descriptor.testTargets.compactMap { $0.pbxTarget.name }, ["AppTests", "FrameworkTests"])
        XCTAssertEqual(
            descriptor.testTargets.map(\.containerPath),
            ["container:App.xcodeproj", "container:Framework/Framework.xcodeproj"]
        )
        XCTAssertEqual(descriptor.testTargets.map(\.isEnabled), [true, true])
        XCTAssertEqual(descriptor.testTargets.map(\.isParallelizable), [false, false])
    }

